package dev.friendai.server.agent.tools;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import dev.friendai.agent.llm.model.ToolSpec;
import dev.friendai.agent.tools.ToolMeta;
import dev.friendai.features.memory.minecraft.tool.MemoryAccess;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import org.junit.jupiter.api.Test;

/**
 * Registry-derived inventory for the capability audit: writes {@code build/tool-inventory.md} and pins the bounds
 * the audit relies on. A tool without a description, a schema over the parameter bound or a duplicate name fails
 * here before a prompt or an LLM ever sees it.
 */
class ToolInventoryTest {
    /** Every tool writes its parameters as an object schema; more than this is not a bounded tool. */
    static final int MAX_PARAMETERS = 16;

    @Test
    void inventoryIsCompleteAndBounded() throws IOException {
        FriendaiTools.Builtins builtins = FriendaiTools.build(() -> 8, MemoryAccess.DISABLED);
        List<ToolSpec> specs = builtins.registry().specs();
        assertFalse(specs.isEmpty(), "the registry must expose tools");

        Set<String> names = new HashSet<>();
        StringBuilder report = new StringBuilder("# Tool inventory\n\n");
        report.append("Generated by `ToolInventoryTest`; every row comes from the live registry.\n\n");
        report.append("| tool | group | plannable | restorable | params | required | description |\n");
        report.append("|---|---|---|---|---:|---|---|\n");
        for (ToolSpec spec : specs) {
            assertTrue(names.add(spec.name()), "duplicate tool name " + spec.name());
            assertFalse(
                    spec.description() == null || spec.description().isBlank(), spec.name() + " has no description");
            var schema = spec.parametersSchema();
            int params = schema.has("properties")
                    ? schema.getAsJsonObject("properties").size()
                    : 0;
            int required =
                    schema.has("required") ? schema.getAsJsonArray("required").size() : 0;
            assertTrue(
                    params <= MAX_PARAMETERS,
                    spec.name() + " exposes " + params + " parameters, above " + MAX_PARAMETERS);
            String group = builtins.catalog()
                    .meta(spec.name())
                    .map(ToolMeta::group)
                    .map(Enum::name)
                    .orElse("-");
            report.append("| `")
                    .append(spec.name())
                    .append("` | ")
                    .append(group)
                    .append(" | ")
                    .append(builtins.plannable().containsKey(spec.name()))
                    .append(" | ")
                    .append(builtins.restorableTaskNames().contains(spec.name()))
                    .append(" | ")
                    .append(params)
                    .append(" | ")
                    .append(required)
                    .append(" | ")
                    .append(spec.description().replace("|", "\\|").replace("\n", " "))
                    .append(" |\n");
        }

        Path out = Path.of("build", "tool-inventory.md");
        Files.createDirectories(out.getParent());
        int specBytes = specs.stream()
                .mapToInt(spec -> (spec.name() + spec.description() + spec.parametersSchema())
                        .getBytes(java.nio.charset.StandardCharsets.UTF_8)
                        .length)
                .sum();
        report.append("\nTotal tools: ")
                .append(specs.size())
                .append("; tool-spec bytes (name + description + schema, UTF-8): ")
                .append(specBytes)
                .append(".\n");
        Files.writeString(out, report.toString());

        // The fixtures the audit names must each have a verb; a missing one is a capability gap, not a zero.
        assertTrue(names.containsAll(List.of(
                "mine_blocks",
                "mine_block_at",
                "clear_area",
                "smelt_items",
                "farm",
                "store_items",
                "milk",
                "go_to",
                "pickup_items")));
    }
}
