package dev.friendai.server.agent.tools;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import dev.friendai.agent.llm.model.ToolSpec;
import dev.friendai.agent.tools.ToolMeta;
import dev.friendai.execution.tool.AccessLevel;
import dev.friendai.execution.tool.ArgValidator;
import dev.friendai.execution.tool.ToolRegistry;
import dev.friendai.features.memory.minecraft.tool.MemoryAccess;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.regex.Pattern;
import java.util.stream.Collectors;
import org.junit.jupiter.api.Test;

/**
 * Registry-derived inventory for the capability audit: writes {@code build/tool-inventory.md} and pins the bounds
 * the audit relies on. Every advertised tool must have catalog metadata, and every shipped example must pass the
 * live schema, so guidance and examples cannot drift away from what the registry really accepts.
 */
class ToolInventoryTest {
    /** Every tool writes its parameters as an object schema; more than this is not a bounded tool. */
    static final int MAX_PARAMETERS = 16;

    /** Named world assertions are separate from this inventory's registry and schema checks. */
    private static final Map<String, String> WORLD_PROOFS = Map.of(
            "go_to", "task: PathingTests#goToWalksAroundPlankWall",
            "mine_blocks", "task: MineBlocksTests#aFreshCompanionMinesTheVisibleBlockBeforeSearching",
            "mine_block_at", "task: MineBlocksTests#mineAtMinesTheWholeVein",
            "pickup_items", "task: MineBlocksTests#mineAtReportsALeftDropThenPickupTakesIt",
            "excavate", "task: ExcavationTests#boxMinesEveryCellAndCollectsDrops",
            "recover_drops", "autonomous: CompanionDeathTests#recoveryWalksBackAndCollectsTheDrops",
            "look_around", "tool: ToolTests#lookAroundListsNearbyLogs");

    @Test
    void inventoryIsCompleteAndBounded() throws IOException {
        FriendaiTools.Builtins builtins = FriendaiTools.build(() -> 8, MemoryAccess.DISABLED);
        List<ToolRegistry.Registration> registrations = builtins.registry().registrations();
        assertFalse(registrations.isEmpty(), "the registry must contribute tools");
        JsonObject examples = examples();

        Set<String> names = new HashSet<>();
        StringBuilder report = new StringBuilder("# Tool inventory\n\n");
        report.append("Generated by `ToolInventoryTest` from all registrations. ")
                .append("Feature and caller filters are also exercised by the live `ToolCatalogTests`.\n\n");
        report.append(
                "| tool | group | cost | feature gate | minimum access | plan action | restorable | checkpoint | params | required | requires | validated example | world test reference | description |\n");
        report.append("|---|---|---|---|---|---|---|---|---:|---:|---|---|---|---|\n");
        StringBuilder guidance = new StringBuilder();
        Set<String> checkpoints = new HashSet<>();
        for (var registration : registrations) {
            ToolSpec spec = registration.spec();
            assertTrue(names.add(spec.name()), "duplicate tool name " + spec.name());
            assertFalse(
                    spec.description() == null || spec.description().isBlank(), spec.name() + " has no description");
            ToolMeta meta = builtins.catalog()
                    .meta(spec.name())
                    .orElseThrow(() -> new AssertionError(spec.name() + " has no catalog entry, so no group, cost or"
                            + " visibility rule reaches the prompt"));
            assertNotNull(meta.group(), spec.name() + " has no catalog group");
            if (!meta.whenToUse().isBlank()) {
                guidance.append("- `")
                        .append(spec.name())
                        .append("` — ")
                        .append(meta.whenToUse().replace("\n", " "))
                        .append('\n');
            }
            var schema = spec.parametersSchema();
            int params = schema.has("properties")
                    ? schema.getAsJsonObject("properties").size()
                    : 0;
            int required =
                    schema.has("required") ? schema.getAsJsonArray("required").size() : 0;
            assertTrue(
                    params <= MAX_PARAMETERS,
                    spec.name() + " exposes " + params + " parameters, above " + MAX_PARAMETERS);
            JsonObject example = examples.has(spec.name()) ? examples.getAsJsonObject(spec.name()) : null;
            if (example != null) {
                List<String> errors = ArgValidator.validate(schema, example);
                assertTrue(
                        errors.isEmpty(),
                        "the shipped example for " + spec.name() + " does not pass its live schema: " + errors);
            }
            var task = builtins.taskTools().get(spec.name());
            String checkpoint = task == null ? null : task.checkpointType();
            if (task != null) {
                assertEquals(task.minAccess(), registration.minAccess(), spec.name() + " direct/queue authority");
                assertEquals(task.plannable(), builtins.plannable().containsKey(spec.name()));
                assertEquals(task.restorable(), builtins.restorableTaskNames().contains(spec.name()));
            }
            if (checkpoint != null) {
                assertTrue(checkpoints.add(checkpoint), "duplicate checkpoint: " + checkpoint);
                assertNotNull(task.checkpointRestorer(), spec.name() + " checkpoint decoder");
            }
            report.append("| `")
                    .append(spec.name())
                    .append("` | ")
                    .append(meta.group().name())
                    .append(" | ")
                    .append(meta.cost())
                    .append(" | ")
                    .append(registration.enabled() ? "-" : "memory and self-knowledge")
                    .append(" | ")
                    .append(registration.minAccess())
                    .append(" | ")
                    .append(builtins.plannable().containsKey(spec.name()))
                    .append(" | ")
                    .append(builtins.restorableTaskNames().contains(spec.name()))
                    .append(" | ")
                    .append(checkpoint == null ? "-" : checkpoint)
                    .append(" | ")
                    .append(params)
                    .append(" | ")
                    .append(required)
                    .append(" | ")
                    .append(String.join("; ", meta.requires()))
                    .append(" | ")
                    .append(example == null ? "-" : "`" + example.toString().replace("|", "\\|") + "`")
                    .append(" | ")
                    .append(WORLD_PROOFS.getOrDefault(spec.name(), "-"))
                    .append(" | ")
                    .append(spec.description().replace("|", "\\|").replace("\n", " "))
                    .append(" |\n");
        }
        assertEquals(
                names,
                builtins.catalog().all().stream().map(ToolMeta::name).collect(Collectors.toSet()),
                "metadata must match registrations even when disabled");
        assertEquals("go_to", builtins.plannable().get("go_to").checkpointType());
        assertTrue(names.contains("show_inventory"), "inventory is directly callable");
        assertFalse(builtins.plannable().containsKey("show_inventory"), "opening a menu is not a plan action");
        for (AccessLevel access : AccessLevel.values()) {
            assertEquals(
                    registrations.stream()
                            .filter(ToolRegistry.Registration::enabled)
                            .filter(r -> access.allows(r.minAccess()))
                            .map(r -> r.spec().name())
                            .toList(),
                    builtins.registry().specs(access).stream()
                            .map(ToolSpec::name)
                            .toList());
        }
        for (var proof : WORLD_PROOFS.entrySet()) {
            assertTrue(names.contains(proof.getKey()), "world proof for unregistered tool: " + proof.getKey());
            var reference = proof.getValue().split(": ", 2)[1].split("#", 2);
            Path source = Path.of("src", "gametest", "java", "dev", "friendai", "test", reference[0] + ".java");
            Pattern gameTest =
                    Pattern.compile("@GameTest(?:\\([^@]*?\\))?\\s+public void " + Pattern.quote(reference[1]) + "\\(");
            assertTrue(gameTest.matcher(Files.readString(source)).find(), "missing " + proof.getValue());
        }
        for (String name : examples.keySet()) {
            assertTrue(names.contains(name), "the example names an unregistered tool: " + name);
        }

        Path out = Path.of("build", "tool-inventory.md");
        Files.createDirectories(out.getParent());
        int specBytes = registrations.stream()
                .map(ToolRegistry.Registration::spec)
                .mapToInt(spec -> (spec.name() + spec.description() + spec.parametersSchema())
                        .getBytes(java.nio.charset.StandardCharsets.UTF_8)
                        .length)
                .sum();
        report.append("\n## Model-facing guidance\n\n").append(guidance);
        report.append("\nTotal tools: ")
                .append(registrations.size())
                .append("; enabled without memory: ")
                .append(builtins.registry().specs().size())
                .append("; catalog groups: ")
                .append(builtins.catalog().all().stream()
                        .map(ToolMeta::group)
                        .distinct()
                        .count())
                .append("; tool-spec bytes (name + description + schema, UTF-8): ")
                .append(specBytes)
                .append("; shipped examples: ")
                .append(examples.size())
                .append(".\n");
        Files.writeString(out, report.toString());

        // The fixtures the audit names must each have a verb; a missing one is a capability gap, not a zero.
        assertTrue(names.containsAll(List.of(
                "mine_blocks",
                "mine_block_at",
                "clear_area",
                "smelt_items",
                "farm",
                "store_items",
                "milk",
                "go_to",
                "pickup_items")));
    }

    private static JsonObject examples() throws IOException {
        try (InputStream stream = ToolInventoryTest.class.getResourceAsStream("/tool-examples.json")) {
            assertNotNull(stream, "tool-examples.json must ship beside the audit");
            JsonElement root = JsonParser.parseReader(new InputStreamReader(stream, StandardCharsets.UTF_8));
            return root.getAsJsonObject();
        }
    }
}
